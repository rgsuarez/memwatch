-- episode-templates.lua: the PUBLIC trajectory templates for the
-- discrimination oracle's dev and train splits (gen-episodes.lua). Each
-- template is a family of offenders the detector tags kind=extreme at grace
-- expiry; the simulator samples a parameter vector per seed and derives the
-- labels from the resulting trajectory, so the intended class below is a
-- design intent, not the label (a burst that would exhaust the machine
-- before finishing is labeled a runaway, and that is the point).
--
-- Rates are MB/s of footprint growth after t = 0; availability is percent
-- of a 36 GB machine at t = 0 (grace expiry); peak0 is the MB/min of the
-- climb on which the detector first tagged the offender, a grace window
-- before t = 0; w0 is the footprint before that climb; age0 is the
-- process's age at t = 0, at least the grace window, the climb and two
-- quiet ticks (the generator refuses a younger one); graceRate (MB/s,
-- optional) is the growth through the grace window, by default the first
-- phase's rate. A history must fit the machine: the offender's footprint
-- net of compression plus what is available, at most 90% of it (the
-- generator refuses more).
-- The sealed evaluation set is generated from a DIFFERENT, private template
-- set, so nothing here can leak into the held-out oracle.

